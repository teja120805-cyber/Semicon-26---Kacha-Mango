"""One-time import of the cross-generator external evaluation surface.

Per reports/V2_ARCHITECTURE_PLAN.md section 9: the reference generator's CODE is
never imported, copied, or adapted into this project. Its already-generated
OUTPUT IMAGES (20 Reference/Search pairs, with ground truth, produced by
actually running the real Applied Materials/Hugging Face reference
generator - not by this project) are copied here as data files only,
strictly as a frozen, external evaluation surface:

- Never used for training or model/checkpoint selection.
- Evaluated with exactly the same pipeline/metrics code as every other
  split.
- Always reported SEPARATELY from V2's own generator splits (never pooled
  into one blended accuracy number) - see evaluation/evaluate.py.

This script only READS from the configured external source directory (set
via --source or the DRIFTSENSE_CROSS_GENERATOR_SOURCE environment variable)
and only WRITES under this project's own data/cross_generator/.

Usage: `python scripts/import_cross_generator_eval_data.py --source <path>`
"""
from __future__ import annotations

import argparse
import os
import shutil

import pandas as pd

DEFAULT_SOURCE = os.environ.get(
    "DRIFTSENSE_CROSS_GENERATOR_SOURCE",
    os.path.join("external", "reference_generator_output", "cross_generator"),
)
DEFAULT_DEST = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data", "cross_generator")


def import_cross_generator_data(source_dir: str = DEFAULT_SOURCE, dest_dir: str = DEFAULT_DEST) -> None:
    if not os.path.isdir(source_dir):
        raise FileNotFoundError(f"Source cross-generator directory not found (read-only lookup): {source_dir}")

    os.makedirs(os.path.join(dest_dir, "reference"), exist_ok=True)
    os.makedirs(os.path.join(dest_dir, "search"), exist_ok=True)

    for kind in ("reference", "search"):
        src_kind_dir = os.path.join(source_dir, kind)
        for name in sorted(os.listdir(src_kind_dir)):
            shutil.copy2(os.path.join(src_kind_dir, name), os.path.join(dest_dir, kind, name))

    manifest = pd.read_csv(os.path.join(source_dir, "manifest.csv"))
    # The source manifest carries stale absolute scratch-directory paths
    # from whatever machine/run produced it; rewrite to paths relative to
    # this project's own data/cross_generator/ layout.
    manifest["reference_path"] = [f"cross_generator/reference/{i:05d}.png" for i in range(len(manifest))]
    manifest["search_path"] = [f"cross_generator/search/{i:05d}.png" for i in range(len(manifest))]
    manifest["source"] = "external_reference_generator"
    manifest.to_csv(os.path.join(dest_dir, "ground_truth.csv"), index=False)
    manifest.to_json(os.path.join(dest_dir, "ground_truth.json"), orient="records", indent=2)

    readme = (dest_dir, "README.md")
    with open(os.path.join(*readme), "w") as f:
        f.write(
            "# Cross-generator external evaluation surface\n\n"
            f"{len(manifest)} Reference/Search pairs, generated by the Applied Materials/Hugging Face reference "
            "generator (not this project's own generator/ package), with ground truth. Copied here as DATA FILES "
            "ONLY - see scripts/import_cross_generator_eval_data.py for provenance and the exact, unmodified "
            "source directory.\n\n"
            "Rules (enforced by convention, not by code - see reports/V2_ARCHITECTURE_PLAN.md section 9):\n"
            "- Never used for training or checkpoint/model selection.\n"
            "- Evaluated with the same pipeline/metrics code as every other split.\n"
            "- Always reported SEPARATELY from V2's own generator splits, never pooled into one number.\n"
        )

    print(f"Imported {len(manifest)} cross-generator pairs -> {dest_dir}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", default=DEFAULT_SOURCE)
    parser.add_argument("--dest", default=DEFAULT_DEST)
    args = parser.parse_args()
    import_cross_generator_data(args.source, args.dest)
